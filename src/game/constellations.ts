/** 結星の等級。数が伸びるほど空が明るくなる */
export interface MagnitudeGrade {
  jp: string;
  la: string;
  mag: number;
}

export function magnitudeOf(chain: number): MagnitudeGrade {
  if (chain >= 89) return { jp: '超新星', la: 'SUPERNOVA', mag: -4 };
  if (chain >= 55) return { jp: '零等星', la: 'MAGNITUDO 0', mag: 0 };
  if (chain >= 34) return { jp: '一等星', la: 'MAGNITUDO I', mag: 1 };
  if (chain >= 21) return { jp: '二等星', la: 'MAGNITUDO II', mag: 2 };
  if (chain >= 13) return { jp: '三等星', la: 'MAGNITUDO III', mag: 3 };
  if (chain >= 8) return { jp: '四等星', la: 'MAGNITUDO IV', mag: 4 };
  if (chain >= 5) return { jp: '五等星', la: 'MAGNITUDO V', mag: 5 };
  return { jp: '六等星', la: 'MAGNITUDO VI', mag: 6 };
}

